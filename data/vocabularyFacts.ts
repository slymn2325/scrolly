const VISUAL_QUERY_STOP_WORDS = new Set([
  'the', 'a', 'an', 'and', 'or', 'of', 'in', 'on', 'at', 'to', 'for', 'from', 'by',
  'with', 'is', 'are', 'was', 'were', 'be', 'been', 'have', 'has', 'had', 'do', 'does',
  'did', 'can', 'could', 'will', 'would', 'should', 'may', 'might', 'that', 'this',
  'these', 'those', 'their', 'they', 'them', 'her', 'his', 'its', 'our', 'your', 'each',
  'every', 'very', 'more', 'most', 'such', 'into', 'over', 'after', 'before', 'about',
  'famous', 'become', 'modern', 'daily', 'present', 'appearing', 'found',
]);

function deriveVisualQuery(item: Partial<VocabularyCard>): string {
  if (typeof item.gifQuery === 'string' && item.gifQuery.trim().length >= 3) {
    return item.gifQuery.trim();
  }
  const tokens = `${item.exampleEn || ''} ${item.definitionEn || ''} ${item.word || ''}`
    .toLowerCase()
    .replace(/[^a-z\s]/g, ' ')
    .split(/\s+/)
    .filter((token) => token.length >= 3 && !VISUAL_QUERY_STOP_WORDS.has(token));

  const unique: string[] = [];
  for (const token of tokens) {
    if (!unique.includes(token)) {
      unique.push(token);
      if (unique.length >= 3) break;
    }
  }
  if (unique.length >= 2) {
    return unique.join(' ');
  }
  const cleanWord = String(item.word || '')
    .toLowerCase()
    .replace(/[^a-z]/g, '')
    .trim();
  return cleanWord ? `${cleanWord} concept` : 'english learning';
}

function normalizeVocabularyCard(item: VocabularyCard): VocabularyCard {
  const cefrLevel =
    typeof item.cefrLevel === 'string' && item.cefrLevel.trim().length > 0
      ? item.cefrLevel.trim().toUpperCase()
      : 'B2';
  const synonyms = Array.isArray(item.synonyms)
    ? item.synonyms
        .map((s) => String(s || '').trim())
        .filter((s) => s.length > 0)
        .slice(0, 3)
    : [];
  const gifQuery = deriveVisualQuery(item);

  return {
    ...item,
    cefrLevel,
    synonyms,
    gifQuery,
  };
}

function mergeVocabularyCards(): VocabularyCard[] {
  const extras = Array.isArray(generatedVocabulary)
    ? (generatedVocabulary as VocabularyCard[])
    : [];
  if (extras.length === 0) return VOCABULARY_FACTS;
  const seen = new Set(VOCABULARY_FACTS.map((item) => item.word.toLowerCase()));
  const merged = [...VOCABULARY_FACTS];
  for (const rawItem of extras) {
    if (!rawItem?.word || seen.has(String(rawItem.word).toLowerCase())) continue;
    seen.add(String(rawItem.word).toLowerCase());
    merged.push(normalizeVocabularyCard(rawItem));
  }
  return merged;
}

export function getVocabularyFacts(): VocabularyCard[] {
  return mergeVocabularyCards();
}

export function findVocabularyById(id: string): VocabularyCard | undefined {
  return getVocabularyFacts().find((item) => item.id === id);
}
