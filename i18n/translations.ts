export function getCategoryMeta(id: CategoryFilter | string): CategoryMeta {
  const normalized =
    id === 'weird_records'
      ? 'records'
      : id === 'language_lab'
        ? 'vocabulary'
        : id === 'istatistik'
          ? 'statistics'
          : id;
  if (normalized === 'vocabulary') {
    return VOCABULARY_META;
  }
  return CATEGORIES.find((c) => c.id === normalized) ?? CATEGORIES[0];
}

